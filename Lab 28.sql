--11. Create trigger for storing updated employee details such as EID, old salary, new salary, old department, 
--new department, and update date into EMPLOYEE_UPDATE_LOG table. 

CREATE TABLE EMPLOYEE_UPDATE_LOG
(
    EID INT,
    OLD_SALARY DECIMAL(10,2) DEFAULT NULL,
    NEW_SALARY DECIMAL(10,2),
    OLD_DEPARTMENT VARCHAR(50) DEFAULT NULL,
    NEW_DEPARTMENT VARCHAR(50),
    UPDATE_DATE DATETIME
);


CREATE TRIGGER EMP_LOG
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    INSERT INTO EMPLOYEE_UPDATE_LOG
    (
        EID,
        OLD_SALARY,
        NEW_SALARY,
        OLD_DEPARTMENT,
        NEW_DEPARTMENT,
        UPDATE_DATE
    )
    SELECT
        (SELECT EID FROM DELETED),
        (SELECT SALARY FROM DELETED),
        (SELECT SALARY FROM INSERTED),
        (SELECT DEPARTMENT FROM DELETED),
        (SELECT DEPARTMENT FROM INSERTED),
        GETDATE();
END;
GO

